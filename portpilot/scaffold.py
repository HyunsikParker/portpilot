"""Write a QNX recursive-make port directory for an upstream project.

Layout (the QNX convention for multi-variant builds):
  <port>/Makefile                 recurse into the OS level
  <port>/common.mk                how to configure, build and install the project
  <port>/nto-<cpu>-<variant>/     one directory per target; its Makefile includes ../common.mk
  <port>/qnx.nto.toolchain.cmake  CMake toolchain that drives qcc/q++ for the selected CPU
The templates below are written for PortPilot; nothing is copied from other port collections.
"""
from pathlib import Path

VARIANTS = {"x86_64": "nto-x86_64-o", "aarch64": "nto-aarch64-le"}

RECURSE_MAKEFILE = """LIST=OS
ifndef QRECURSE
QRECURSE=recurse.mk
ifdef QCONFIG
QRDIR=$(dir $(QCONFIG))
endif
endif
include $(QRDIR)$(QRECURSE)
"""

TOOLCHAIN = """# CMake toolchain for QNX 8.0, generated by PortPilot.
# Needs QNX_HOST and QNX_TARGET from qnxsdp-env.sh; CPU is x86_64 or aarch64le.
foreach(var QNX_HOST QNX_TARGET)
  if("$ENV{${var}}" STREQUAL "")
    message(FATAL_ERROR "${var} is not set; source qnxsdp-env.sh first")
  endif()
  file(TO_CMAKE_PATH "$ENV{${var}}" ${var})
endforeach()
set(QNX TRUE)
set(CMAKE_SYSTEM_NAME QNX)
if(CMAKE_HOST_WIN32)
  set(_exe ".exe")
endif()
set(CMAKE_C_COMPILER   "${QNX_HOST}/usr/bin/qcc${_exe}")
set(CMAKE_CXX_COMPILER "${QNX_HOST}/usr/bin/q++${_exe}")
set(CMAKE_AR     "${QNX_HOST}/usr/bin/nto${CPU}-ar${_exe}"     CACHE FILEPATH "archiver")
set(CMAKE_RANLIB "${QNX_HOST}/usr/bin/nto${CPU}-ranlib${_exe}" CACHE FILEPATH "ranlib")
set(_target "-Vgcc_nto${CMAKE_SYSTEM_PROCESSOR}")
# Cache entries (not *_INIT) so that languages enabled later in a subdirectory, e.g. enable_language(CXX) for tests,
# also compile and link for the target instead of qcc's default x86_64.
set(CMAKE_C_FLAGS   "${_target} ${PORTPILOT_C_FLAGS}" CACHE STRING "C flags")
set(CMAKE_CXX_FLAGS "${_target} ${PORTPILOT_C_FLAGS}" CACHE STRING "C++ flags")
set(CMAKE_EXE_LINKER_FLAGS    "${_target} ${PORTPILOT_LD_FLAGS}" CACHE STRING "exe linker flags")
set(CMAKE_SHARED_LINKER_FLAGS "${_target} ${PORTPILOT_LD_FLAGS}" CACHE STRING "shared linker flags")
set(CMAKE_MODULE_LINKER_FLAGS "${_target} ${PORTPILOT_LD_FLAGS}" CACHE STRING "module linker flags")
set(CMAKE_FIND_ROOT_PATH "${QNX_TARGET};${QNX_TARGET}/${CPUVARDIR};${PORTPILOT_STAGE}/${CPUVARDIR}")
set(CMAKE_FIND_ROOT_PATH_MODE_PROGRAM NEVER)
set(CMAKE_FIND_ROOT_PATH_MODE_LIBRARY ONLY)
set(CMAKE_FIND_ROOT_PATH_MODE_INCLUDE ONLY)
set(CMAKE_FIND_ROOT_PATH_MODE_PACKAGE ONLY)
"""

CMAKE_COMMON = """# Port of {name} for QNX 8.0, generated by PortPilot.
# Build: source qnxsdp-env.sh; QNX_PROJECT_ROOT=<path to {name} source> make -C <this directory> install
ifndef QCONFIG
QCONFIG=qconfig.mk
endif
include $(QCONFIG)
include $(MKFILES_ROOT)/qmacros.mk

NAME={name}
PREFIX ?= /usr/local
STAGE ?= $(INSTALL_ROOT_$(OS))
CMAKE_BUILD_TYPE ?= Release
BUILD_TESTING ?= OFF

# Fixes applied by PortPilot (see PORTING.md for the error each one answers)
PORT_CFLAGS  := {cflags}
PORT_LDFLAGS := {ldflags}

ALL_DEPENDENCIES = portpilot_all
.PHONY: portpilot_all install check clean
include $(MKFILES_ROOT)/qtargets.mk

CMAKE_ARGS = -DCMAKE_TOOLCHAIN_FILE=$(PROJECT_ROOT)/qnx.nto.toolchain.cmake \\
             -DCMAKE_SYSTEM_PROCESSOR=$(CPUVARDIR) -DCPU=$(CPU) -DCPUVARDIR=$(CPUVARDIR) \\
             -DCMAKE_INSTALL_PREFIX=$(STAGE)/$(CPUVARDIR)/$(PREFIX) \\
             -DCMAKE_INSTALL_INCLUDEDIR=$(STAGE)/$(PREFIX)/include \\
             -DCMAKE_BUILD_TYPE=$(CMAKE_BUILD_TYPE) \\
             -DPORTPILOT_C_FLAGS="$(PORT_CFLAGS) -I$(STAGE)/$(PREFIX)/include" \\
             -DPORTPILOT_LD_FLAGS="$(PORT_LDFLAGS)" -DPORTPILOT_STAGE=$(STAGE) \\
             {test_arg}{extra}

portpilot_all:
\t@mkdir -p build
\tcd build && cmake $(CMAKE_ARGS) $(QNX_PROJECT_ROOT)
\tcd build && $(MAKE) all VERBOSE=1

install check: portpilot_all
\tcd build && $(MAKE) install

clean:
\trm -rf build
"""


def write_port(dest, name, *, cflags=("-D_QNX_SOURCE",), ldflags=(), test_switch="BUILD_TESTING", extra_cmake=(),
               cpus=("x86_64", "aarch64")):
    """Create dest/<files>. Returns the list of written paths."""
    dest = Path(dest)
    dest.mkdir(parents=True, exist_ok=True)
    written = []

    def put(rel, text):
        p = dest / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
        written.append(p)

    put("Makefile", RECURSE_MAKEFILE)
    put("qnx.nto.toolchain.cmake", TOOLCHAIN)
    test_arg = f"-D{test_switch}=$(BUILD_TESTING)" if test_switch else ""
    extra = "".join(f" \\\n             {a}" for a in extra_cmake)
    put("common.mk", CMAKE_COMMON.format(name=name, cflags=" ".join(cflags), ldflags=" ".join(ldflags),
                                         test_arg=test_arg, extra=extra))
    for cpu in cpus:
        put(f"{VARIANTS[cpu]}/Makefile", "include ../common.mk\n")
    return written
